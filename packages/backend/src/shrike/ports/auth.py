from datetime import datetime
from typing import Protocol

from pydantic import SecretStr

from shrike.domain.access import RepositoryGrant
from shrike.domain.auth import SavedSession, UserCredential, UserIdentity


class UserAuthorizationGateway(Protocol):
    def exchange(self, code: str, verifier: str) -> UserCredential: ...

    def identity(self, token: SecretStr) -> UserIdentity: ...

    def grants(self, token: SecretStr) -> tuple[RepositoryGrant, ...]: ...


class SessionStore(Protocol):
    def save_state(self, digest: str, verifier: str, expiry: datetime) -> None: ...
    def consume_state(self, digest: str) -> str | None: ...
    def create(
        self, digest: str, identity: UserIdentity, token: SecretStr, expiry: datetime
    ) -> None: ...
    def read(self, digest: str) -> SavedSession | None: ...
    def revoke(self, digest: str) -> None: ...
